function ensureDir(filePath) {
  const dir = path.dirname(path.join(root, filePath));
  if (!dryRun) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function writeFile(filePath, content) {
  const abs = path.join(root, filePath);
  const exists = fs.existsSync(abs);

  if (exists && !force) {
    return { action: "skipped", path: filePath, reason: "exists" };
  }

  ensureDir(filePath);

  if (!dryRun) {
    fs.writeFileSync(abs, content, "utf8");
  }

  return { action: exists ? "overwritten" : "created", path: filePath };
}

function main() {
  console.log("Integrity Foundation Generator");
  console.log(`Mode: ${dryRun ? "dry-run" : "write"}`);
  console.log(`Overwrite existing: ${force ? "yes" : "no"}`);
  console.log(`Include CI workflow: ${includeCi ? "yes" : "no"}`);

  const results = filesToGenerate.map((file) => writeFile(file.path, file.content));

  const created = results.filter((r) => r.action === "created").length;
  const overwritten = results.filter((r) => r.action === "overwritten").length;
  const skipped = results.filter((r) => r.action === "skipped").length;

  console.log("\nResults:");
  for (const result of results) {
    if (result.action === "skipped") {
      console.log(`  - skipped: ${result.path} (${result.reason})`);
    } else {
      console.log(`  - ${result.action}: ${result.path}`);
    }
  }

  console.log("\nSummary:");
  console.log(`  created: ${created}`);
  console.log(`  overwritten: ${overwritten}`);
  console.log(`  skipped: ${skipped}`);

  console.log("\nCommands:");
  console.log("  node scripts/generate-integrity-foundation.mjs --dry-run");
  console.log("  node scripts/generate-integrity-foundation.mjs");
  console.log("  node scripts/generate-integrity-foundation.mjs --force");
  console.log("  node scripts/generate-integrity-foundation.mjs --no-ci");
}

main();
